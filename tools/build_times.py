"""Builds first and last train times from GTFS timetables.
Writes www/js/times-<city>.js with, for every pair of neighbouring stations "a>b",
[first departure, last departure] from a towards b, in minutes after midnight (can pass 1440 after midnight).
Usage: python3 tools/build_times.py <city> <gtfs folder> <weekday service ids> <sunday service ids> "<note shown in the app>" [rough]
"rough" marks first-train times as unreliable (Delhi: the feed has no early trains that start mid-line).
"""
import csv, json, math, re, sys, collections, os
city, GTFS, WK, SUN, NOTE = sys.argv[1], sys.argv[2], sys.argv[3].split(','), sys.argv[4].split(','), sys.argv[5]
ROUGH = len(sys.argv) > 6 and sys.argv[6] == 'rough'
HERE = os.path.dirname(os.path.abspath(__file__))
src = open(f'{HERE}/../www/js/data-{city}.js', encoding='utf-8').read()
D = json.loads(src[src.index('=', src.index('window.NET.' + city)) + 1:].rstrip().rstrip(';'))
S = D['stations']
def slug(n): return re.sub(r'[^a-z0-9]+', '-', n.lower()).strip('-')
def hav(a, b, c, d):
    p = math.pi / 180
    h = math.sin((c-a)*p/2)**2 + math.cos(a*p)*math.cos(c*p)*math.sin((d-b)*p/2)**2
    return 12742 * math.asin(math.sqrt(h))
rd = lambda f: list(csv.DictReader(open(f'{GTFS}/{f}', encoding='utf-8-sig')))
# neighbours in the app's network
adj = set()
for l in D['lines']:
    st = l['st']
    for i in range(len(st) - 1): adj.add((st[i], st[i+1])); adj.add((st[i+1], st[i]))
    if l.get('loop'): adj.add((st[-1], st[0])); adj.add((st[0], st[-1]))
# timetable stop -> app station: same name first, otherwise the nearest station within 400 m
alias = {}
for k, v in S.items():
    alias[slug(v['n'])] = k
    for a in v.get('a', []): alias.setdefault(slug(a), k)
stop_to = {}; unmatched = []
for r in rd('stops.txt'):
    sid = alias.get(slug(r['stop_name']))
    if not sid and r.get('stop_lat'):
        la, lo = float(r['stop_lat']), float(r['stop_lon'])
        best = min(S, key=lambda k: hav(la, lo, S[k]['lat'], S[k]['lon']))
        if hav(la, lo, S[best]['lat'], S[best]['lon']) < 0.4: sid = best
    if sid: stop_to[r['stop_id']] = sid
    else: unmatched.append(r['stop_name'])
service = {r['trip_id']: r['service_id'] for r in rd('trips.txt')}
def mins(t):
    h, m, s = map(int, t.split(':')); return h * 60 + m + (1 if s >= 30 else 0)
by_trip = collections.defaultdict(list)
for r in rd('stop_times.txt'):
    if service.get(r['trip_id']) in WK + SUN: by_trip[r['trip_id']].append((int(r['stop_sequence']), r['stop_id'], r['departure_time'] or r['arrival_time']))
out = {'wk': {}, 'sun': {}}
for tid, rows in by_trip.items():
    rows.sort(); which = 'wk' if service[tid] in WK else 'sun'
    for (_, a, dep), (_, b, _) in zip(rows, rows[1:]):
        A, B = stop_to.get(a), stop_to.get(b)
        if not A or not B or (A, B) not in adj: continue
        m = mins(dep); key = A + '>' + B; cur = out[which].get(key)
        out[which][key] = [m, m] if not cur else [min(cur[0], m), max(cur[1], m)]
total = len(adj)
print(city, 'pairs with weekday times', len(out['wk']), 'of', total, '| sunday', len(out['sun']), '| stops not matched:', sorted(set(unmatched))[:12])
js = '/* generated by tools/build_times.py - do not edit by hand */\n' + f'window.NET.{city}.tt=' + json.dumps(out['wk'], separators=(',', ':')) + f';\nwindow.NET.{city}.ttSun=' + json.dumps(out['sun'], separators=(',', ':')) + f';\nwindow.NET.{city}.ttSrc=' + json.dumps(NOTE) + f';\nwindow.NET.{city}.ttRough=' + ('true' if ROUGH else 'false') + ';\n'
open(f'{HERE}/../www/js/times-{city}.js', 'w', encoding='utf-8').write(js)
